import { readFileSync, writeFileSync } from "node:fs";

const assetDirectory = new URL("../assets/", import.meta.url);
const sources = [
    "about.txt",
    "projects/research-note/en.txt",
    "projects/research-note/ko.txt",
    "projects/research-note/references.txt",
    "projects/scopus_papers.csv"
];
const textContent = Object.fromEntries(sources.map((filename) => {
    const source = new URL(filename, assetDirectory);
    const text = readFileSync(source, "utf8").replace(/^\uFEFF/, "");
    return [filename, text.split("\n")];
}));

const output = new URL("text-content-fallback.js", assetDirectory);
const generated = "// Generated by node scripts/build-text-fallback.mjs. Edit the source text and CSV files.\n";
writeFileSync(output, generated + `globalThis.siteTextFallback = ${JSON.stringify(textContent, null, 4)};\n`);
